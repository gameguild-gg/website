export interface FormulaLearnerPrompt {
  // Generated by the server for grading-enabled formula runtime. It gives the
  // learner enough data to answer without exposing the hidden formula.
  variables: Record<string, number>
  expectedResult: number
  decimalPlaces?: number
}

export type FormulaLearnerEntry = LearnerEntry<
  FormulaEntry,
  "formula" | "toleranceType" | "tolerance"
> & {
  prompt?: FormulaLearnerPrompt
}

